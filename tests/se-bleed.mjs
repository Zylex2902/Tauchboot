import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process', '--no-zygote', "--headless='shell'"].includes(a)) });
const ctx = await browser.newContext({ viewport: { width: 667, height: 375 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message));
await page.goto('http://localhost:4173/?test', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__hull.scenes.every(Boolean), null, { timeout: 20000 });
const at = (x, y) => [(667 - 480) / 2 + x, (375 - 270) / 2 + y];
const idle = () => page.waitForFunction(() => !window.__hull.travel, null, { timeout: 8000 });
const r = {};
let [x, y] = at(Math.round((217 + 263) / 2), 270 + 12); await page.touchscreen.tap(x, y); await page.waitForTimeout(200); await idle();
r.tapBelowStrip = await page.evaluate(() => window.__hull.station);
[x, y] = at(470, 270 + 10); await page.touchscreen.tap(x, y); await page.waitForTimeout(500);
r.pauseFromBleed = await page.evaluate(() => window.__hull.pause.isPaused);
[x, y] = at(470, 270 + 10); await page.touchscreen.tap(x, y); await page.waitForTimeout(500);
r.resumedFromBleed = !(await page.evaluate(() => window.__hull.pause.isPaused));
[x, y] = at(240, 26); await page.touchscreen.tap(x, y); await page.waitForTimeout(600);
r.voiceTapBelowTab = await page.evaluate(() => window.__hull.voice.isOpen);
[x, y] = at(240, 200); await page.touchscreen.tap(x, y); await page.waitForTimeout(600);
r.voiceClosedByScrim = !(await page.evaluate(() => window.__hull.voice.isOpen));
console.log(JSON.stringify({ errs, r }));
await browser.close();
