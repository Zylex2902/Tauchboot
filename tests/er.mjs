import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const OUT = '/tmp/claude-0/shots';
const VW = +(process.argv[2] ?? 960), VH = +(process.argv[3] ?? 540);
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process', '--no-zygote', "--headless='shell'"].includes(a)) });
const ctx = await browser.newContext({ viewport: { width: VW, height: VH }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()));
await page.goto('http://localhost:4173/?test&fresh', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__hull.scenes.every(Boolean), null, { timeout: 30000 });
await page.evaluate(() => { window.__noSave = true; });
await page.keyboard.press('Enter');
await page.waitForTimeout(600);
await page.evaluate(() => { window.__hull.goTo(7); window.__sim.command({ type: 'boatSet', set: { telegraph: 1, ordered: 40, hand: false } }); });
await page.waitForTimeout(3000);
await page.screenshot({ path: `${OUT}/er-${VW}.png` });
await page.evaluate(() => { window.__sim.state.boat.power.bat = 0.06; });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${OUT}/er-low.png` });
await page.evaluate(() => { window.__sim.state.boat.power.bat = 0.0002; });
await page.waitForTimeout(5000);
await page.screenshot({ path: `${OUT}/er-flat.png` });
console.log(JSON.stringify({ errs, p: await page.evaluate(() => window.__obs.boat.power) }));
await browser.close();
