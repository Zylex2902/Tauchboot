import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const OUT = process.argv[2] ?? '/tmp/claude-0/shots';
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process','--no-zygote',"--headless='shell'"].includes(a)), headless: true });
const ctx = await browser.newContext({ viewport: { width: 852, height: 393 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto('http://localhost:4173/?test', { waitUntil: 'networkidle' });
await page.waitForTimeout(600);
await page.evaluate(() => { __hull.goTo(5); });
await page.waitForTimeout(900);
const ct = () => page.evaluate(() => !!__hull.scenes[5]);
console.log('scene', await ct());
const set = (fn) => page.evaluate(fn);
await page.screenshot({ path: `${OUT}/ct-housed.png` });
await set(() => { const c = __hull.scenes[5].controls; c.get('raise').emit(0.55); });
await page.waitForTimeout(300);
await page.screenshot({ path: `${OUT}/ct-under.png` });
await set(() => { const c = __hull.scenes[5].controls; c.get('raise').emit(1); c.get('train').emit(__drill.bearing() / 45 + 0.1); });
await page.waitForTimeout(400);
await page.screenshot({ path: `${OUT}/ct-low.png` });
await set(() => { const c = __hull.scenes[5].controls; c.get('mag').emit(1); c.get('train').emit(__drill.bearing() / 45); });
await page.waitForTimeout(600);
await page.screenshot({ path: `${OUT}/ct-high.png` });
const info = await set(() => {
  const d = __drill; const k = d.ship.cls; const mast = { coaster: 17, freighter: 27, tanker: 21 }[k];
  const deg = Math.atan(mast / d.range()) * 180 / Math.PI;
  const c = __hull.scenes[5].controls; c.get('stad').emit(deg / 0.5); c.get('cls').emit(['coaster','freighter','tanker'].indexOf(k));
  return { k, range: d.range(), aob: d.aob(), b: d.bearing() };
});
await page.waitForTimeout(700);
await page.screenshot({ path: `${OUT}/ct-stad.png` });
const perf = await set(() => { const v = __hull.scenes[5].view; const t0 = performance.now(); for (let i = 0; i < 30; i++) v.render(40); return (performance.now() - t0) / 30; });
console.log(JSON.stringify({ info, perf, errs }));
await browser.close();
