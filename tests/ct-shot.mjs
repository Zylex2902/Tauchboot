import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const OUT = process.argv[2] ?? '/tmp/claude-0/shots';
const Q = process.argv[3] ?? '';
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process', '--no-zygote', "--headless='shell'"].includes(a)) });
const ctx = await browser.newContext({ viewport: { width: 960, height: 540 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', e => errs.push(e.message)); page.on('console', m => m.type() === 'error' && errs.push(m.text()));
await page.goto('http://localhost:4173/?test&fresh' + Q, { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__hull.scenes.every(Boolean), null, { timeout: 30000 });
await page.evaluate(() => { window.__noSave = true; });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/cr-card.png` });
await page.keyboard.press('Enter');
await page.waitForTimeout(600);
await page.evaluate(() => window.__hull.goTo(5));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${OUT}/ct.png` });
console.log(JSON.stringify({ errs, boat: await page.evaluate(() => ({ d: window.__obs.boat.depth, set: window.__obs.boat.set })) }));
await browser.close();
