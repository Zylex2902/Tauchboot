import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const dpr = Number(process.argv[2] || 2);
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process', '--no-zygote', "--headless='shell'"].includes(a)) });
const ctx = await browser.newContext({ viewport: { width: 852, height: 393 }, deviceScaleFactor: dpr, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
page.on('pageerror', e => console.log('ERR', e.message));
await page.goto('http://localhost:4173/?test', { waitUntil: 'networkidle' });
await page.waitForFunction(() => window.__hull.scenes.every(Boolean), null, { timeout: 20000 });
const fm = () => page.evaluate(() => new Promise(r => { const t=[]; const f=(x)=>{t.push(x); if(t.length<20) requestAnimationFrame(f); else r(Math.round((t[19]-t[0])/19));}; requestAnimationFrame(f); }));
console.log('idle control room', await fm());
const trav = (i) => page.evaluate((i) => new Promise(r => { const h = window.__hull; const rec=[]; const t0=performance.now(); h.goTo(i); const f=()=>{ rec.push([Math.round(performance.now()-t0), h.transit.x]); if (h.travel) requestAnimationFrame(f); else r(rec); }; requestAnimationFrame(f); }), i);
console.log('travel 3->0', JSON.stringify(await trav(0)));
console.log('idle bow', await fm());
console.log('travel 0->8', JSON.stringify(await trav(8)));
console.log('idle dc', await fm());
console.log('travel 8->3', JSON.stringify(await trav(3)));
console.log('idle cr again', await fm());
await page.waitForTimeout(3000);
console.log('idle cr later', await fm());
await browser.close();
