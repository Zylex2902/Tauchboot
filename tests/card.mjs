import { chromium } from 'playwright';
import sp from '@sparticuz/chromium';
const OUT = '/tmp/claude-0/shots';
const browser = await chromium.launch({ executablePath: await sp.executablePath(), args: sp.args.filter(a => !['--single-process','--no-zygote',"--headless='shell'"].includes(a)), headless: true });
const ctx = await browser.newContext({ viewport: { width: 852, height: 393 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto('http://localhost:4173/?test', { waitUntil: 'networkidle' });
await page.waitForTimeout(6000);
await page.screenshot({ path: `${OUT}/brief.png` });
await page.keyboard.press('Enter');
await page.waitForTimeout(800);
const ph = await page.evaluate(() => __drill && window.__hull && JSON.stringify({}));
await page.evaluate(() => { __hull.goTo(5); });
await page.waitForTimeout(900);
await page.evaluate(() => { const c = __hull.scenes[5].controls; c.get('raise').emit(1); c.get('train').emit(__drill.bearing() / 45); c.get('mag').emit(1);
  const d = __drill; const mast = { coaster: 17, freighter: 27, tanker: 21 }[d.ship.cls];
  c.get('cls').emit(['coaster','freighter','tanker'].indexOf(d.ship.cls)); c.get('stad').emit(Math.atan(mast / d.range()) * 180 / Math.PI / 0.5 * 1.03); });
await page.waitForTimeout(800);
await page.screenshot({ path: `${OUT}/scope2.png` });
await page.evaluate(() => __hull.scenes[5].controls.get('markRange').emit(1));
await page.waitForTimeout(6500);
await page.screenshot({ path: `${OUT}/report.png` });
console.log(JSON.stringify({ errs }));
await browser.close();
