await page.goto('http://localhost:4173/?test', { waitUntil: 'networkidle' });
await page.waitForTimeout(4000);
const v = await page.evaluate(() => window.__vib);
console.log(v.length); console.log([...new Set(v)].slice(0,5).join('\n\n'));
